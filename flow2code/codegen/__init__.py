"""Code generation: build a block tree from the graph, then render it as Python."""
from __future__ import annotations

from typing import Optional

import networkx as nx

from ..graph import build, validate
from .ast_builder import If, Raw, Seq, While, build_tree   # the tree types, for tests
from .emitter import render, text                      # and the two ways to print it

__all__ = ["generate", "build_tree", "If", "While", "Seq", "Raw", "render", "text"]


def generate(fc, g: Optional[nx.DiGraph] = None, annotate: bool = False,
             header: bool = True, check: bool = True) -> str:
    """A whole Python program for ``fc``.

    ``annotate=True`` puts the source block id at the end of each line, which is what makes
    the generator explainable on stage.  ``check=True`` re-parses the result with ``ast`` so
    a broken program can never be handed to the runner.
    """
    g = g if g is not None else validate(fc, build(fc))
    tree = build_tree(fc, g)
    body = text(tree, annotate=annotate)
    lines = []
    if header:
        lines.append(f"# generated by Flow2Code from {fc.name!r} — "
                     f"{len(fc.nodes)} blocks, {len(fc.edges)} arrows")
        lines.append("# every line below comes from one block of the chart; nothing here is typed")
        lines.append("")
    lines.append(body)
    src = "\n".join(lines) + "\n"
    if check:
        import ast
        try:
            ast.parse(src)
        except SyntaxError as exc:                    # pragma: no cover - a generator bug
            raise AssertionError(f"the generator produced code that does not parse: "
                                 f"{exc.msg}\n{src}") from None
    return src
